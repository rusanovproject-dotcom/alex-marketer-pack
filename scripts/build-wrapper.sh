#!/usr/bin/env bash
# build-wrapper.sh — генерит обёртку .claude/agents/marketer.md из core.md.
# Паттерн дизайнера (#52) и копирайтера (#61): @include в теле субагента НЕ
# работает (тело = system prompt дословно), поэтому обёртка = frontmatter +
# ПОЛНОЕ тело core.md. Запуск: после каждой правки core.md. Идемпотентно.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../../../.." && pwd)"   # корень офиса (где .claude/)
CORE="$ROOT/office/agents/marketer/core.md"
OUT="$ROOT/.claude/agents/marketer.md"

[ -f "$CORE" ] || { echo "✗ нет core.md: $CORE"; exit 1; }

# Папки .claude/agents/ может не быть (свежий офис). Без этого редирект в $OUT
# падал, а финальная строка всё равно печатала зелёную галочку — ученик получал
# «✓ обёртка сгенерена» и никакого агента.
mkdir -p "$(dirname "$OUT")"

# tools: Bash обязателен (внешняя сверка гонит yt-transcript.sh и греп по офису),
# Skill обязателен (вызов чужих зарегистрированных скиллов — /offer,
# /hormozi и семья /direct-*). Без них агент не может ни снять транскрипт, ни
# позвать чужой скилл — это дыра, которую чиним этой сборкой.
# MCP-группы НЕ дописывать: telegram-mcp и прочие не установлены, мёртвая группа
# в tools — урок дизайнера (ARCHITECTURE.md §8).
# Agent — обязателен: skills/jtbd/SKILL.md требует ревьюера на отборе сегментов и
# критика — оба «отдельным субагентом с чистым контекстом». Это единственные две точки
# цикла, где артефакт видит кто-то кроме автора; рубрика прямо признаёт, что без них
# самооценка вырождается («автор склонен ставить себе проход»). Без Agent обе процедуры
# неисполнимы, и агент отыгрывал бы критика сам — ровно то, против чего они написаны.
TOOLS='Read, Write, Edit, Bash, Grep, Glob, WebSearch, WebFetch, Skill, Agent'

# ВАЖНО: снести существующий файл/симлинк перед записью, иначе запись пойдёт в
# target симлинка (обёртки в офисе исторически бывали симлинками).
rm -f "$OUT"

{
  echo "---"
  echo "name: marketer"
  echo "description: >-"
  echo "  Алекс — маркетолог-навигатор. Находит точку приложения усилий, где деньги жирные именно для этого бизнеса, и доводит её до цифры. Семь тактов: физика и точка → деньги назад (обратная воронка от прибыли, предельный CPL, гейт маржи) → спрос и сегменты → голос рынка → конкуренты и свободное место → обещание и продуктовая лестница → путь клиента с узким местом → гипотеза с критерием. Сквозной market-to-funnel ведёт от фактуры рынка до принятого владельцем типа воронки и GROWTH-PLAN.md. Три закона: не выдумывай (внешняя сверка с источником), помечай вес знания 🟢🟡🔴⚪, ищи AI-рычаг с эффектом и сроком замера. Критик-гейт A-F вслух с цитатами. TRIGGERS: маркетолог, алекс, распакуй ЦА, сегменты, ICP, идеальный клиент, позиционирование, продуктовая лестница, ревизия маркетинга, где у меня деньги, сколько нужно лидов, посчитай воронку, узкое место, какую гипотезу проверяем, где здесь ИИ даст эффект, был созвон, вот транскрипт, конкуренты, с чем нас сравнивают, упакуй оффер, оцени оффер, разбери буллиты, какие воронки в моей нише, кастдев без клиентов, поставил тебя — с чего начать, проведи меня от рынка до воронки, маркетинговый навигатор, подготовь проект к воронке, быстрый маркетинговый разбор для эфира. ANTI-TRIGGERS: тексты, посты, заголовки, голос → Copywriter; вёрстка, визуал, лендинг как дизайн → Designer; запуск и координация → Producer; КП и ведение сделки → Hermes; финальный круг жирности уже прогнанного оффера → Equalizer (если есть в офисе); рекламный кабинет и семантика → Яндекс-Директолог; непрерывный мониторинг конкурентов → Аргус."
  echo "model: opus"
  echo "tools: $TOOLS"
  echo "memory: project"
  echo "---"
  echo ""
  # Якорь дома: у субагента CWD — корень офиса, а весь core.md написан путями от
  # папки агента. Без этой строки таблица роутинга указывает в пустоту (P1-8).
  echo "**Моя папка — office/agents/marketer/ от корня офиса. Все пути в этом тексте — от неё; в командах указывай их полностью от корня.**"
  echo ""
  # тело core.md БЕЗ его собственного frontmatter (первый ---...--- блок)
  awk 'NR==1 && $0=="---"{f=1; next} f && $0=="---"{f=0; next} !f{print}' "$CORE"
} > "$OUT"

echo "✓ обёртка сгенерена: $OUT ($(wc -l < "$OUT") строк)"
